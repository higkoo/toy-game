#!/usr/bin/env python3
"""把完整 Noto Serif CJK TTC 抽成视频用到的字形子集。

为什么要子集化：完整 `NotoSerifCJK.ttc` 约 26 MB，进 git 仓库会让 clone 变慢，
而 HyperFrames 的 lint 要求 `@font-face` 必须带 `url()` 源（只写 `local()` 会
报 `font_face_local_only`，写系统字体名会报 `font_family_without_font_face`）——
也就是说字体文件必须随工程走，才能保证任何机器上渲染出同样的字形。

做法：扫 `index.html` 里出现的全部 CJK 字符，连同 ASCII 与常用标点一起，
用 fontTools 的 subsetter 抽出 SC 子集并重命名为独立字体 `SanjiSerif`。

用法：
    python3 scripts/make_font_subset.py
    # -> assets/SanjiSerif-subset.ttf（约 285 KB）

依赖：
    pip install fonttools
    # 完整字体来源：系统安装的 Noto Serif CJK，或
    # https://github.com/notofonts/noto-cjk/releases
"""

from __future__ import annotations

import io
import os
import re
import sys

try:
    from fontTools import subset
    from fontTools.ttLib import TTCollection, TTFont
except ImportError:  # pragma: no cover
    sys.exit("缺少 fonttools，请先执行：pip install fonttools")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX = os.path.join(ROOT, "index.html")
OUT = os.path.join(ROOT, "assets", "SanjiSerif-subset.ttf")

# 完整字体来源：优先用工程内已有的 ttc，其次找系统安装的
CANDIDATES = [
    os.path.join(ROOT, "assets", "NotoSerifCJK.ttc"),
    "/usr/share/fonts/opentype/noto/NotoSerifCJK-Regular.ttc",
]

# ASCII 可见字符 + 常用中文标点与符号（视频里可能出现但不在文本节点里的）
EXTRA = "".join(chr(c) for c in range(0x20, 0x7F)) + (
    "　、。〃〈〉《》「」『』【】〔〕・ー－—…‰′″‹›※°′″℃¥§№·→←↑↓★☆■□▲△●○◆◇♪♫"
)


def collect_chars() -> str:
    """扫 index.html 的所有文本节点，收集 CJK 字符。"""
    with open(INDEX, encoding="utf-8") as fh:
        html = fh.read()
    chars: set[str] = set()
    for text in re.findall(r">([^<>]+)<", html):
        for ch in text:
            if ch.strip() and ord(ch) > 0x2000:
                chars.add(ch)
    return "".join(sorted(chars | set(EXTRA)))


def pick_sc_font(coll: TTCollection) -> TTFont:
    """ttc 里通常有 JP/KR/SC/TC/HK 五个成员，取 SC。"""
    for font in coll.fonts:
        if font["name"].getDebugName(4) == "Noto Serif CJK SC":
            return font
    return coll.fonts[0]


def rename(font: TTFont, family: str) -> None:
    """把字体内部名改成独立家族名，避免与系统 Noto Serif CJK SC 混淆。"""
    name = font["name"]
    values = {
        0: "Subset of Noto Serif CJK SC, generated by scripts/make_font_subset.py. SIL Open Font License 1.1.",
        1: family,
        3: f"{family}:Subset",
        4: family,
        6: family,
        16: family,
    }
    for nid, value in values.items():
        name.removeNames(nameID=nid)
        name.setName(value, nid, 3, 1, 0x409)
        name.setName(value, nid, 1, 0, 0)


def pin_timestamps(font: TTFont) -> None:
    """固定 head.created / head.modified。

    还要在构造 TTFont 时传 recalcTimestamp=False —— 否则 fontTools 保存前会
    把 head.modified 改写成当前时间，导致同一份源码每次生成的字节流都不同。
    """
    epoch = 3600 * 24 * 365 * 24  # 2024-01-01 00:00:00 UTC
    if "SOURCE_DATE_EPOCH" in os.environ:
        epoch = int(os.environ["SOURCE_DATE_EPOCH"])
    font["head"].created = epoch
    font["head"].modified = epoch


def main() -> None:
    src = next((p for p in CANDIDATES if os.path.exists(p)), None)
    if src is None:
        sys.exit(
            "找不到完整字体来源。请把 NotoSerifCJK.ttc 放到 assets/，"
            "或安装系统的 Noto Serif CJK 后重试。"
        )

    chars = collect_chars()
    # recalcTimestamp=False：保存时不要把 head.modified 改写成当前时间，
    # 否则同一份源码每次生成的字节流都不同，无法比对复现。
    coll = TTCollection(src, lazy=False, recalcTimestamp=False)
    font = pick_sc_font(coll)

    opts = subset.Options()
    opts.desubroutinize = True
    opts.retain_gids = False
    opts.layout_features = "*"
    opts.name_IDs = ["*"]
    opts.name_legacy = True
    opts.notdef_outline = True
    opts.recalc_bounds = True

    sub = subset.Subsetter(options=opts)
    sub.populate(text=chars)
    sub.subset(font)
    font.flavor = None
    rename(font, "SanjiSerif")
    pin_timestamps(font)

    buf = io.BytesIO()
    # recalcTimestamp=False：否则 fontTools 会把 head.modified 改写成当前时间，
    # 导致同一份源码每次生成的字节流都不同。
    font.save(buf, reorderTables=None)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "wb") as fh:
        fh.write(buf.getvalue())

    print(f"字符集 {len(chars)} 个 -> {OUT}（{len(buf.getvalue()) / 1024:.1f} KB）")


if __name__ == "__main__":
    main()
