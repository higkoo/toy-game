def E(t, h, c, o, g):
    return {"t": t, "h": h, "c": c, "o": o, "g": g}

def mk(fname, title, sub, q, intro, groups):
    entries = []
    SRC = '文化史话整理 · ' + title
    for t, rows in groups:
        for h, c, g in rows:
            entries.append(E(t, h, c, SRC, g))
    return {"title": title, "file": fname, "sub": sub, "q": q,
            "intro": intro, "entries": entries}

